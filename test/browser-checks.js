// Run against the running sample with Playwright CLI:
// playwright-cli open http://127.0.0.1:4317
// playwright-cli run-code --filename test/browser-checks.js
async page => {
  const results = [];
  const assert = (condition, message) => { if (!condition) throw new Error(message); results.push(message); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const origin = new URL(page.url()).origin;
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ colorScheme: 'light' });
  await page.evaluate(() => { localStorage.removeItem('logview.theme'); localStorage.removeItem('logview.sidebarCollapsed'); });
  await page.reload();
  const search = page.getByRole('searchbox', { name: 'Search logs' });
  const entries = page.getByRole('listbox', { name: 'Select a log entry' }).getByRole('option');
  await entries.filter({ hasText: 'Customer loaded' }).waitFor();
  await page.getByRole('button', { name: 'Ⅱ Pause', exact: true }).click();
  await search.fill('Singapore');
  assert(await entries.count() === 1, 'Search includes collapsed nested values');
  await page.getByRole('button', { name: 'Expand', exact: true }).click();
  assert(await page.getByText('city:"Singapore"', { exact: true }).isVisible(), 'Nested objects expand to capture-time values');
  assert(!(await page.locator('#values').innerText()).includes('Changed AFTER'), 'Later object mutations do not alter snapshots');
  await page.getByRole('button', { name: 'Collapse', exact: true }).click();
  assert(await page.locator('#values details[open]').count() === 0, 'Collapse closes every branch');
  await page.getByRole('button', { name: 'Expand', exact: true }).click();
  assert(await page.locator('#values details:not([open])').count() === 0, 'Expand opens every captured branch');
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'], { origin });
  await page.getByRole('button', { name: 'Copy JSON' }).click();
  await page.getByRole('status').filter({ hasText: 'Snapshot JSON copied' }).waitFor();
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert(JSON.parse(copied)[1].type === 'object', 'Copy JSON produces a structured snapshot');
  const downloadWait = page.waitForEvent('download');
  await page.getByRole('button', { name: '↓ Export' }).click();
  const download = await downloadWait;
  await download.saveAs('output/playwright/export.json');
  assert(download.suggestedFilename().endsWith('.json'), 'Export downloads filtered log JSON');
  await search.fill('');
  await page.getByRole('button', { name: /^Errors / }).click();
  assert(await entries.count() === 2, 'Error filter isolates errors and failed assertions');
  await page.getByRole('button', { name: /^Warnings / }).click();
  assert(await entries.count() >= 1, 'Warning filter shows warnings');
  await page.getByRole('button', { name: 'Debug', exact: true }).click();
  assert(await entries.count() >= 1, 'Debug filter shows debug messages');
  await page.getByRole('button', { name: 'Output', exact: true }).click();
  assert(await entries.count() >= 2, 'Output filter shows raw stream writes');
  await page.getByRole('button', { name: /^All \d/ }).click();
  const billing = page.getByRole('button', { name: /^Billing \d/ });
  if (await billing.count()) {
    await billing.click();
    assert(await entries.count() >= 1, 'Project filter isolates the second Node app');
    assert((await entries.allTextContents()).every(text => text.includes('Invoice delayed')), 'Second-project logs are inspectable');
    await page.getByRole('button', { name: /^All projects/ }).click();
  }
  const beforePause = await entries.count();
  await page.waitForTimeout(6500);
  assert(await entries.count() === beforePause, 'Pause freezes the displayed log stream');
  await page.getByRole('button', { name: /^▶ Resume/ }).click();
  await page.waitForTimeout(100);
  assert(await entries.count() > beforePause, 'Resume includes logs captured while paused');
  await page.getByRole('button', { name: 'Clear view' }).click();
  assert(await entries.count() === 0, 'Clear view hides existing logs');
  await page.reload();
  await entries.filter({ hasText: 'Customer loaded' }).waitFor();
  assert(await entries.count() > 0, 'Reload restores collector history');
  await page.getByRole('checkbox', { name: 'Follow' }).uncheck();
  await entries.filter({ hasText: 'Customer loaded' }).click();
  await page.getByRole('button', { name: 'Expand', exact: true }).click();
  const layout = await page.evaluate(() => ({
    row: document.querySelector('.entry').getBoundingClientRect().height,
    inspector: document.querySelector('#inspector-panel').getBoundingClientRect().width,
    panes: document.querySelector('.panes').getBoundingClientRect().width,
    list: document.querySelector('#entries').getBoundingClientRect().height
  }));
  assert(layout.row <= 30, 'Log entries use compact single-line rows');
  assert(layout.inspector / layout.panes >= .6, 'Inspector receives at least 60 percent of the workspace');
  assert(Math.floor(layout.list / layout.row) >= 24, 'Desktop shows at least 24 log rows at once');
  const expandedWidth = await page.locator('main').evaluate(element => element.getBoundingClientRect().width);
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  assert(await page.locator('main').evaluate(element => element.getBoundingClientRect().width) > expandedWidth, 'Minimizing the sidebar reclaims workspace width');
  await page.reload();
  await entries.filter({ hasText: 'Customer loaded' }).waitFor();
  assert(await page.getByRole('button', { name: 'Expand sidebar', exact: true }).isVisible(), 'Sidebar preference survives a reload');
  await page.getByRole('button', { name: 'Expand sidebar', exact: true }).click();
  assert(await page.getByRole('navigation', { name: 'Projects', exact: true }).isVisible(), 'Sidebar can be restored');
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Follow' }).uncheck();
  await entries.filter({ hasText: 'Customer loaded' }).click();
  await page.getByRole('button', { name: 'Expand', exact: true }).click();
  const openBranches = await page.locator('#values details[open]').count();
  await page.getByRole('button', { name: /Full screen/ }).click();
  const dialog = page.getByRole('dialog', { name: 'Inspector', exact: true });
  assert(await dialog.isVisible(), 'Inspector opens as a native full-screen modal');
  assert(await page.locator('#inspector-modal-body #inspector-panel').count() === 1, 'Full-screen view reuses the same inspector');
  assert(await dialog.getByText('city:"Singapore"', { exact: true }).isVisible(), 'Full screen preserves selected values and expanded branches');
  const modalBounds = await dialog.boundingBox();
  assert(modalBounds.width === 1440 && modalBounds.height === 1000, 'Full-screen inspector fills the entire viewport');
  await page.getByRole('combobox', { name: 'Inspector color theme', exact: true }).selectOption('dark');
  assert(await page.locator('html').getAttribute('data-theme') === 'dark', 'Dark mode applies inside the full-screen inspector');
  await page.getByRole('button', { name: 'Copy JSON' }).click();
  await dialog.getByRole('status').filter({ hasText: 'Snapshot JSON copied' }).waitFor();
  assert(await dialog.getByRole('status').filter({ hasText: 'Snapshot JSON copied' }).isVisible(), 'Copy feedback is visible above the modal');
  await page.getByRole('button', { name: 'Close full-screen inspector' }).focus();
  await page.keyboard.press('Tab');
  assert(await page.evaluate(() => document.querySelector('#inspector-modal').contains(document.activeElement)), 'Keyboard focus stays inside the modal');
  await page.screenshot({ path: 'output/playwright/inspector-fullscreen-dark.png' });
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.querySelector('#inspector-panel').parentElement.id === 'panes');
  assert(await page.locator('#values details[open]').count() === openBranches, 'Closing full screen preserves expanded tree state');
  assert(await page.evaluate(() => document.activeElement.id) === 'inspector-fullscreen', 'Closing restores focus to the full-screen button');
  await page.getByRole('button', { name: /Full screen/ }).click();
  await page.getByRole('button', { name: 'Close full-screen inspector' }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.querySelector('#inspector-panel').parentElement.id === 'panes');
  assert(await page.locator('#panes #inspector-panel').count() === 1, 'Close button restores the inspector without duplicates');
  await page.reload();
  await entries.filter({ hasText: 'Customer loaded' }).waitFor();
  assert(await page.locator('html').getAttribute('data-theme') === 'dark', 'Dark theme preference survives a reload');
  const theme = page.getByRole('combobox', { name: 'Color theme', exact: true });
  assert(await theme.inputValue() === 'dark', 'Theme control reflects the saved preference');
  await theme.selectOption('system');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.emulateMedia({ colorScheme: 'light' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  assert(await theme.inputValue() === 'system', 'System theme responds to operating system changes');
  await theme.selectOption('light');
  await page.getByRole('checkbox', { name: 'Follow' }).uncheck();
  await entries.filter({ hasText: 'Customer loaded' }).click();
  await page.getByRole('button', { name: 'Expand', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/desktop-light.png' });
  await theme.selectOption('dark');
  await page.screenshot({ path: 'output/playwright/desktop-dark.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Expand sidebar', exact: true }).click();
  assert(await page.getByRole('complementary', { name: 'Workspace navigation' }).isVisible(), 'Mobile users can open project navigation');
  await page.getByRole('button', { name: 'Close sidebar', exact: true }).click();
  assert(await page.getByRole('complementary', { name: 'Workspace navigation' }).isHidden(), 'Mobile navigation closes cleanly');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout fits without horizontal page overflow');
  await page.screenshot({ path: 'output/playwright/mobile.png', fullPage: true });
  await page.getByRole('button', { name: /Full screen/ }).click();
  const mobileBounds = await dialog.boundingBox();
  assert(mobileBounds.width === 390 && mobileBounds.height === 844, 'Full-screen inspector also fits mobile viewports');
  await page.screenshot({ path: 'output/playwright/inspector-fullscreen-mobile.png' });
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  const bounds = await page.evaluate(() => ({ stream: document.querySelector('.stream').getBoundingClientRect().bottom, panes: document.querySelector('.panes').getBoundingClientRect().bottom }));
  assert(bounds.stream <= bounds.panes + 1, 'Desktop stream scrolls inside its panel');
  await page.screenshot({ path: 'output/playwright/desktop.png' });
  assert(errors.length === 0, `No browser runtime errors (${errors.length})`);
  return { passed: results.length, checks: results };
}
